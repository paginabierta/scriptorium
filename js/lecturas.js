// Llena las citas vacías de los bloques «Cita bíblica» según su etiqueta (Primera lectura, Salmo, Segunda lectura, Evangelio)
export function fillLecturas(blocks, date) {
  const r = lecturasPara(date);
  if (!r) return blocks;
  const pick = (label = '') => {
    const t = label.toLowerCase();
    if (/primera|1\.?\s*ª?\s*lect/.test(t)) return r.l1;
    if (/salmo/.test(t)) return r.sal;
    if (/segunda|2\.?\s*ª?\s*lect/.test(t)) return r.l2;
    if (/evangelio/.test(t)) return r.ev;
    if (/procesi/.test(t)) return r.procesion || '';
    return '';
  };
  for (const b of blocks || []) {
    if (b.type === 'biblia' && b.data && !String(b.data.ref || '').trim()) {
      const v = pick(b.data.label);
      if (v) b.data.ref = v;
    }
  }
  return blocks;
}
