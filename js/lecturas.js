// Devuelve { l1, sal, l2, ev, procesion? } o null si no hay lecturas propias para ese día
export function lecturasPara(date) {
  const lit = liturgicalDay(date);
  if (!lit.clave) return null;
  const v = L[lit.clave + "|" + lit.ciclo];
  if (!v) return null;
  const [l1, sal, l2, ev, procesion] = v;
  return { l1, sal, l2, ev, ...(procesion ? { procesion } : {}), clave: lit.clave, ciclo: lit.ciclo };
}

// Solo el Evangelio (primera opción si hay forma larga y breve)
export function evangelioPara(date) {
  const r = lecturasPara(date);
  return r ? r.ev.split(" o bien ")[0] : "";
}

export function vaticanUrl(date) {
  const [y, m, dd] = isoDate(date).split("-");
  return `https://www.vaticannews.va/es/evangelio-de-hoy/${y}/${m}/${dd}.html`;
}

// Lecturas como líneas cortas para mostrar
export function lecturasHtml(r, esc) {
  if (!r) return "";
  const row = (k, v) => v ? `<li><span class="lec-k">${k}</span><span class="lec-v">${esc(v)}</span></li>` : "";
  return `<ul class="lecturas">${row("1.ª lectura", r.l1)}${row("Salmo", r.sal)}${row("2.ª lectura", r.l2)}${row("Evangelio", r.ev)}${r.procesion ? row("Procesión", r.procesion) : ""}</ul>`;
}

